def default_instructions(nodes):
    result = {
        f"guide:{key}": {
            "key": f"guide:{key}",
            "title": title,
            "body": body,
            "steps": steps,
            "revision": 0,
        }
        for key, title, body, steps in GUIDES
    }
    for key, title, body, steps in DRIVER_GUIDES:
        result[f"drivers:{key}"] = {
            "key": f"drivers:{key}",
            "title": title,
            "body": body,
            "steps": steps,
            "revision": 0,
        }
    by_id = {node["id"]: node for node in nodes}
    for node in nodes:
        chain, current = [], node
        while current:
            chain.insert(0, current)
            current = by_id.get(current["parent_id"])
        rules = {rule for ancestor in chain for rule in ancestor["rules"]}
        hints = list(dict.fromkeys(ancestor["hint"] for ancestor in chain if ancestor["hint"]))
        steps = [
            "Проверьте данные водителя и выбранные категории.",
            "Опишите ситуацию в комментарии.",
            "Проверьте обращение и нажмите «Сохранить».",
        ]
        if "phone_change" in rules:
            steps = [
                "Откройте Октелл и карточку водителя в диспетчерской рядом.",
                "Сверьте номер телефона: он должен быть виден на обоих экранах.",
                "Сделайте общий скриншот двух экранов и приложите его к обращению.",
                "В комментарии укажите старый номер, новый номер и ссылку на аккаунт водителя.",
                "Включите «Формировать тикет», проверьте данные и сохраните обращение.",
            ]
        elif "transaction" in rules:
            steps = [
                "Найдите транзакцию в диспетчерской и укажите её номер / РРН.",
                "Добавьте ссылку на аккаунт водителя в комментарий.",
                "Приложите скриншот или опишите проблему.",
                "Если деньги несколько раз возвращались на баланс, "
                "предложите сменить карту вывода.",
                "Сформируйте и сохраните тикет.",
            ]
        elif "account_link" in rules:
            steps = [
                "Скопируйте ссылку на аккаунт водителя из диспетчерской в комментарий.",
                "Заполните дополнительные поля и приложите обязательные файлы по инструкции выше.",
                "Включите «Формировать тикет» и сохраните обращение.",
            ]
        elif "cooperation" in rules:
            steps = [
                "Укажите название компании.",
                "Укажите номер для обратного звонка и предлагаемую услугу.",
                "При необходимости добавьте комментарий или вложения.",
                "Сохраните обращение.",
            ]
        elif "employee" in rules:
            steps = [
                "Укажите имя сотрудника.",
                "Опишите ситуацию в комментарии.",
                "Проверьте отдел и сохраните обращение.",
            ]
        key = f"category:{node['id']}"
        result[key] = {
            "key": key,
            "title": node["label"],
            "body": "\n\n".join(hints)
            or "Зафиксируйте причину обращения. Комментарий поможет коллегам понять ситуацию.",
            "steps": steps,
            "revision": 0,
        }
    return result
