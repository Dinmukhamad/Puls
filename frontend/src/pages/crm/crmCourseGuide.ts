/** The step the lesson waits for and its instruction; none once every step passed. */
export function courseStep(task: CrmTrainingTask | undefined) {
  const index = task?.steps.findIndex(step => step.status !== "passed") ?? -1;
  if (!task || index < 0) return null;
  const step = task.steps[index];
  return { index, step, guide: COURSE_GUIDE[task.key]?.steps[step.key] };
}

/** Practice is done without step-by-step hints, so nothing is lit up there. */
export function courseTarget(task: CrmTrainingTask | undefined): CourseTarget | undefined {
  if (!task || task.state !== "in_progress" || task.key === "crm_practice_v2") return undefined;
  return courseStep(task)?.guide?.target;
}
